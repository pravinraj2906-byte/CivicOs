const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('../citizen-app/node_modules/typescript');
const code = ts.transpileModule(fs.readFileSync(__dirname+'/browser-api.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2021,esModuleInterop:true}}).outputText;
const values=new Map(); const exportsObj={};
const context={exports:exportsObj,require:p=>p==='./fixtures.json'?JSON.parse(fs.readFileSync(__dirname+'/fixtures.json','utf8')):require(p),localStorage:{getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)},Date,JSON,Set,console};
vm.runInNewContext(code,context);
const api=exportsObj.demoAdapter;
const call=async(url,method='get',data={},token='',params={})=>(await api({url,method,data,params,headers:{Authorization:'Bearer '+token}})).data;
(async()=>{
  const citizen=await call('/auth/login','post',{email:'citizen.priya@example.com'});
  const officer=await call('/auth/login','post',{email:'officer.anita@civicos.gov'});
  const ct=citizen.access_token,ot=officer.access_token;
  const created=await call('/grievances','post',{title:'Test pothole',description:'Synthetic road pothole for evaluation',location:'Demo street'},ct);
  assert.equal(created.department,'Public_Works'); assert.equal(created.ai_source,'BROWSER_DEMO_RULES');
  await call('/officer/grievances/'+created.id+'/status','patch',{status:'RESOLVED',remarks:'Simulated completion'},ot);
  assert.equal((await call('/grievances/'+created.id,'get',{},ct)).status,'RESOLVED');
  await call('/citizens/me/grievances/'+created.id+'/feedback','post',{is_resolved:false,comment:'Demo issue persists'},ct);
  assert.equal((await call('/grievances/'+created.id,'get',{},ct)).status,'IN_PROGRESS');
  await assert.rejects(()=>call('/officer/grievances','get',{},ct),e=>e.response.status===403);
  const other=await call('/auth/login','post',{email:'citizen.ramesh@example.com'});
  await assert.rejects(()=>call('/grievances/'+created.id,'get',{},other.access_token),e=>e.response.status===403);
  const feed=await call('/feed','get',{},ct);assert.ok(feed.items.some(g=>g.id===created.id));assert.equal(feed.items[0].is_verified,false);
  const confirmed=await call('/feed/'+created.id+'/confirm','post',{},ct);assert.equal(confirmed.community_count,1);
  assert.equal((await call('/feed/'+created.id+'/confirm','post',{},ct)).community_count,1);
  const matches=await call('/schemes/assistant','post',{query:'farmer'},ct);assert.equal(matches.source,'BROWSER_DEMO_RULES');assert.ok(matches.matches.length>0);assert.equal(matches.matches[0].confidence,0);
  await assert.rejects(()=>call('/auth/register','post',{name:'Real user'}),e=>e.response.status===400);
  assert.ok(values.get('civicos_evaluation_v1').includes('Test pothole'));
  console.log('PASS: citizen report, officer update, citizen reopen, role/ownership boundaries, feed, idempotent confirmation, indicative scheme matching, disabled signup, local persistence.');
})().catch(e=>{console.error(e);process.exitCode=1});
